local tracker = require('core.tracker')
local sessions = require('core.sessions')
local rules = require('data.phoenix_rules')
local json = require('json')
local checks = 0
local function equal(a, b, label)
    checks = checks + 1
    assert(a == b, label .. ': expected ' .. tostring(b) .. ', got ' .. tostring(a))
end
local function copy(value) return json.decode(json.encode(value)) end
local function snapshot(values)
    local result = { valid = true, id = 100, job = 1, job_name = 'WAR', level = 30, effective_level = 30,
        zone = 100, exp = 1000, exp_needed = rules.tnl[30], limit_mode = false, gil_current = 10000 }
    for key, value in pairs(values or {}) do result[key] = value end
    return result
end
local state = tracker.new()
equal(state:observe_gil(10000, 0), false, 'Packets cannot seed unidentified tracker')
state:observe(snapshot(), 0)
equal(state:view(0).gil.current, 10000, 'Client snapshot seeds wallet')
state:observe(snapshot({ gil_current = 11000 }), 1)
equal(state:view(1).gil.current, 10000, 'Polling cannot consume pending packet delta')
state:observe_gil(11000, 1)
equal(state:view(1).gil.gained, 1000, 'Packet records gil delta')
equal(state.started, nil, 'Gil does not start EXP clock')
equal(state:view(61).rate, nil, 'Gil cannot create EXP per hour')
equal(state:view(61).gil.rate, 60000, 'Gil rate starts independently')
state:award({ kind = 'exp', amount = 100 }, 61)
equal(state:view(62).elapsed, 1, 'EXP clock starts at EXP award')
equal(state:view(62).gil.elapsed, 61, 'EXP award does not restart gil clock')
state:pause(70, true)
state:observe_gil(5000, 100)
equal(state:view(100).gil.current, 5000, 'Paused tracker updates wallet')
equal(state:view(100).gil.spent, 0, 'Paused tracker excludes spending')
state:pause(110, false)
state:observe(snapshot({ gil_current = 5000 }), 110)
state:observe_gil(4900, 111)
equal(state:view(111).gil.spent, 100, 'Resume retains paused wallet baseline')
state.gil:discontinuity(120)
equal(state:view(120).session_exp, 100, 'Inventory gap keeps EXP totals')
equal(state:view(120).gil.current, nil, 'Inventory gap clears only wallet')
state:observe_gil(8000, 130)
equal(state:view(130).gil.gained, 1000, 'Inventory gap delta is not guessed')
state:observe(snapshot({ zone = 101, gil_current = 9000 }), 140)
equal(state:view(140).gil.current, 9000, 'New zone seeds fresh wallet')
equal(state:view(140).gil.gained, 1000, 'Zoning never backfills gil')
state:reset(141, true)
equal(state:view(141).gil.current, 9000, 'Session reset keeps current gil')
equal(state:view(141).gil.net, 0, 'Session reset clears gil totals')
equal(state:view(141).gil.rate, nil, 'Session reset clears gil rate')
state:observe_gil(9100, 142)
local saved = copy(state:export(202))
equal(saved.gil.gained, 100, 'Nested gil counters saved')
equal(saved.gil.current, nil, 'Saved session has no wallet baseline')
local restored = tracker.new()
equal(restored:restore(saved, 10000, snapshot()), true, 'Matching session restores gil')
equal(restored:view(10000).gil.current, nil, 'Restored wallet starts unknown')
restored:observe(snapshot({ gil_current = 100 }), 10001)
equal(restored:view(10001).gil.spent, 0, 'Offline wallet changes excluded')
equal(restored:view(10001).gil.gained, 100, 'Saved gil total retained')
equal(restored:view(10001).gil.elapsed, 60, 'Offline gil time excluded')
local legacy = copy(saved)
legacy.gil = nil
equal(restored:restore(legacy, 10100), true, 'Older version-one session still loads')
equal(restored:view(10100).gil.net, 0, 'Legacy session starts with no gil totals')
local invalid = copy(saved)
invalid.gil.paused = true
equal(restored:restore(invalid, 10200), false, 'Saved gil must share session pause state')
invalid = copy(saved)
invalid.gil.gained = -1
equal(restored:restore(invalid, 10200), false, 'Bad nested gil rejects whole restore')
equal(restored:view(10200).gil.net, 0, 'Rejected nested restore is atomic')
state:pause(203, true)
equal(restored:restore(copy(state:export(204)), 11000), true, 'Paused gil session restores')
restored:observe(snapshot({ gil_current = 800 }), 11000)
restored:observe_gil(900, 11001)
equal(restored:view(11001).gil.gained, 100, 'Paused restore keeps counting paused')
equal(restored:view(11100).gil.elapsed, 61, 'Paused restore keeps clock paused')
local unavailable = snapshot()
unavailable.gil_current = nil
restored:observe(unavailable, 11101)
equal(restored:view(11101).gil.current, nil, 'Unknown inventory in valid snapshot clears stale wallet')
equal(restored:view(11101).gil.gained, 100, 'Unknown inventory preserves session gil totals')

local files, writes = {}, 0
local options = {
    read = function(path) return copy(files[path] or {}) end,
    write = function(path, data) files[path] = copy(data); writes = writes + 1; return true end,
    clock = function() return 1700000000 end,
}
local manager = sessions.new('memory', options)
state = manager:select(snapshot(), 0)
equal(writes, 1, 'New session initially saved')
state:observe_gil(10200, 1)
manager:checkpoint(29)
equal(writes, 1, 'Gil does not trigger per-frame writes')
manager:checkpoint(30)
equal(writes, 2, 'Gil-only activity checkpoints on schedule')
equal(state.started, nil, 'Gil-only saved session still has no EXP clock')
local loaded = sessions.new('memory', options)
local resumed, did_resume = loaded:select(snapshot({ gil_current = 40000 }), 1000)
equal(did_resume, true, 'Gil-only session resumes from store')
resumed:observe(snapshot({ gil_current = 40000 }), 1000)
equal(resumed:view(1000).gil.gained, 200, 'Gil-only gains persisted')
equal(resumed:view(1000).gil.elapsed, 29, 'Gil-only elapsed persisted')
equal(resumed:view(1000).gil.current, 40000, 'Current wallet refreshed after resume')
equal(resumed:view(1000).session_exp, 0, 'Gil-only resume invents no EXP')

resumed:pause(1001, true)
resumed:observe_gil(40100, 1002)
loaded:checkpoint(1002, true)
local after_reload = sessions.new('memory', options)
state, did_resume = after_reload:select(snapshot({ gil_current = 50000 }), 2000)
state:observe(snapshot({ gil_current = 50000 }), 2000)
equal(did_resume, true, 'Paused gil-only session resumes after reload')
equal(state.paused, true, 'Reload preserves pause')
equal(state:view(2000).gil.current, 50000, 'Paused reload refreshes current wallet')
equal(state:view(2000).gil.gained, 200, 'Paused and unloaded gains are excluded')
equal(state:view(2000).gil.elapsed, 30, 'Paused reload excludes offline time')
state:pause(2001, false)
state:observe_gil(49950, 2002)
equal(state:view(2002).gil.spent, 50, 'Resume after reload uses fresh wallet baseline')

local other_job = snapshot({ job = 2, job_name = 'MNK', gil_current = 60000 })
state = after_reload:select(other_job, 2003)
state:observe(other_job, 2003)
equal(state:view(2003).gil.gained, 0, 'Another job starts its own gil totals')
equal(state:view(2003).gil.spent, 0, 'Another job does not inherit spending')
state:observe_gil(60150, 2004)
equal(state:view(2064).gil.rate, 9000, 'Other job keeps its own active gil clock')
local returning = snapshot({ gil_current = 70000 })
state, did_resume = after_reload:select(returning, 2065)
state:observe(returning, 2065)
equal(did_resume, true, 'Returning job resumes saved gil totals')
equal(state:view(2065).gil.current, 70000, 'Returning job gets current wallet')
equal(state:view(2065).gil.gained, 200, 'Other job gains are not counted again')
equal(state:view(2065).gil.spent, 50, 'Returning job restores its spending')
equal(state:view(2065).gil.elapsed, 32, 'Time on another job is excluded')
state:observe_gil(69900, 2066)
equal(state:view(2066).gil.spent, 150, 'Returning job counts new changes')

local other_character = snapshot({ id = 200, gil_current = 90000 })
state = after_reload:select(other_character, 2070)
state:observe(other_character, 2070)
equal(state:view(2070).gil.current, 90000, 'Another character seeds its own wallet')
equal(state:view(2070).gil.net, 0, 'Another character cannot inherit session gil')
state:observe_gil(90100, 2071)
returning.gil_current = 80000
state, did_resume = after_reload:select(returning, 2080)
state:observe(returning, 2080)
equal(did_resume, true, 'Original character resumes its saved session')
equal(state:view(2080).gil.gained, 200, 'Other character gains stay separate')
equal(state:view(2080).gil.spent, 150, 'Original character spending is retained')
equal(state:view(2080).gil.current, 80000, 'Original character gets a fresh wallet baseline')
local old_id = after_reload:current().id
state = assert(after_reload:new_session(2081))
equal(after_reload:current().id ~= old_id, true, 'Reset starts a separate saved session')
equal(state:view(2081).gil.net, 0, 'New saved session clears gil totals')
equal(state:view(2081).gil.current, 80000, 'New saved session keeps current gil')
equal(state:view(2081).gil.rate, nil, 'New saved session clears gil rate')
return checks .. ' assertions'
