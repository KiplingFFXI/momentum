local checks = 0;
local function equal(actual, expected, label)
    checks = checks + 1;
    assert(actual == expected, label .. ': ' .. tostring(actual) .. ' ~= ' .. tostring(expected));
end
local defaults, imgui = require('ui.defaults'), require('imgui');
local saved = defaults.make();
saved.alerts.food_enabled, saved.alerts.food_sound = true, 'My alert.wav';
saved.window.open, saved.window.tab = true, 'Alerts';
MOCK.settings_file = saved;
local sound = require('core.sound');
MOCK.fs[sound.BUILT_IN], MOCK.fs[sound.WORKER] = true, true;
MOCK.fs[sound.FOLDER] = false;
MOCK.fs[sound.BUILT_IN .. 'My alert.wav'] = true;
MOCK.sound_contents = { [sound.BUILT_IN .. 'My alert.wav'] = 'original audio' };
MOCK.dirs = { [sound.BUILT_IN] = { 'My alert.wav' } };
local clipboard;
imgui.SetClipboardText = function(value) clipboard = value; end;
MOCK.load_addon();
local app = MOMENTUM_TEST;
equal(#(MOCK.sound_copies or {}), 0, 'Loading the addon never copies audio');
equal(app.services.sound_folder(), sound.FOLDER, 'Requesting the folder path returns the permanent location');
equal(MOCK.fs[sound.FOLDER], true, 'The explicit folder-path action prepares a missing sound folder');
MOCK.frame(0.3);
equal(app.services.sound_location('My alert.wav').kind, 'addon', 'Alerts sees the current addon-folder source');
equal(#(MOCK.sound_copies or {}), 0, 'Drawing a sound selection never copies it');
MOCK.clicks['Copy sound folder path'] = true;
MOCK.frame(0.3);
equal(clipboard, sound.FOLDER, 'The visible folder button copies the actual permanent path');
MOCK.clicks['Copy to permanent folder'] = true;
MOCK.frame(0.3);
equal(#(MOCK.sound_copies or {}), 1, 'The explicit Alerts action copies exactly one sound');
equal(MOCK.sound_contents[sound.FOLDER .. 'My alert.wav'], 'original audio', 'The permanent copy keeps the original bytes');
equal(MOCK.fs[sound.BUILT_IN .. 'My alert.wav'], true, 'The original sound is retained');
equal(app.settings().alerts.food_sound, 'My alert.wav', 'Copying preserves the saved alert filename');
equal(#(MOCK.sound_workers or {}), 0, 'Copying never opens a decoder');
for _ = 1, 120 do MOCK.frame(1 / 60); end
equal(#MOCK.sound_copies, 1, 'Later frames never repeat the file copy');
MOCK.fs[sound.BUILT_IN .. 'My alert.wav'] = false;
MOCK.dirs[sound.BUILT_IN] = {};
sound.invalidate();
equal(app.services.sound_location('My alert.wav').kind, 'permanent', 'Removing the replaceable copy leaves the permanent sound available');
MOCK.clicks['Play##food_sound'] = true;
MOCK.frame(0.3);
equal(#MOCK.sound_workers, 1, 'The same saved alert can still play after addon replacement');
equal(MOCK.sound_workers[1].path, sound.FOLDER .. 'My alert.wav', 'Playback falls back to the permanent copy');
equal(#MOCK.sound_copies, 1, 'Playback does not repeat the copy');
equal(app.settings().alerts.food_sound, 'My alert.wav', 'The selected sound survives replacement unchanged');
equal(#MOCK.commands, 0, 'Storage controls send no gameplay commands');
MOCK.fire('unload');
return { count = checks };
