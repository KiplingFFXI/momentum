local profiles = require('ui.profiles');
local history = require('ui.history');
local defaults = require('ui.defaults');
local store = require('core.file_store');
local folder = MOCK_INSTALL_PATH .. '/config/addons/momentum/';
ashita.fs.create_dir(folder);
local saved = profiles.new(folder);
local s = defaults.make();
s.display.order[1], s.display.order[2] = s.display.order[2], s.display.order[1];
s.display.divider = ' / ';
s.display.alignment = 'right';
s.display.label_position = 'after';
s.job_links['1'] = 'Private';
s.window.x = 999;
s.shared = true;
s.bar.anchor, s.bar.start = 'top', 135;
assert(saved:save('Leveling', s));
local other = defaults.make();
other.window.x = 42;
other.job_links['1'] = 'Own';
assert(saved:load('Leveling', other));
assert(other.display.order[1] == 'progress' and other.display.divider == ' / ');
assert(other.display.alignment == 'right');
assert(other.display.label_position == 'after');
assert(other.bar.anchor == 'top' and other.bar.start == 135);
assert(other.window.x == 42 and other.job_links['1'] == 'Own' and other.shared == false);
other.display.labels.progress = 'Changed';
local again = defaults.make();
assert(saved:load('Leveling', again));
assert(again.display.labels.progress ~= 'Changed');
assert(not saved:save('', s));
assert(not saved:save('None', s));
assert(not saved:save('hidden##label', s));
local file = assert(io.open(folder .. 'profiles.json', 'rb'));
local baseline = file:read('*a'); file:close();
MOCK.file_replace_error = true;
assert(not saved:save('Cannot write', s));
file = assert(io.open(folder .. 'profiles.json', 'rb'));
assert(file:read('*a') == baseline); file:close();
MOCK.file_replace_error = false;
file = assert(io.open(folder .. 'profiles.json', 'wb')); file:write('{ broken'); file:close();
assert(not saved:save('Keep broken', s));
assert(not saved:delete('Leveling'));
file = assert(io.open(folder .. 'profiles.json', 'rb'));
assert(file:read('*a') == '{ broken'); file:close();
assert(store.write(folder .. 'profiles.json', {}));
assert(saved:save('Keep', s));
assert(saved:delete('Keep'));
assert(#saved:names() == 0);
local h = history.new();
for i = 1, 12 do local before = history.copy(s); s.bar.height = 20 + i; h:push(before); end
assert(#h.entries == 8);
local actual_window = s.window;
assert(h:undo(s) and s.bar.height == 31 and s.window == actual_window);
return 'Profiles: order/dividers, isolation, corrupt files, atomic failure, delete, and eight-step undo passed.';
