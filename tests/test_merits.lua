local tracker = require('core.tracker')
local goals = require('core.goals')
local packets = require('core.packets')
local notifications = require('core.notifications')
local rules = require('data.phoenix_rules')
local checks = 0
local function equal(actual, expected, label)
    checks = checks + 1
    assert(actual == expected, label .. ': expected ' .. tostring(expected) .. ', got ' .. tostring(actual))
end
local function near(actual, expected, label)
    checks = checks + 1
    assert(actual and math.abs(actual - expected) < 0.001, label .. ': expected ' .. tostring(expected) .. ', got ' .. tostring(actual))
end
local function snapshot(values)
    local result = { valid = true, id = 100, job = 1, job_name = 'WAR', level = 75, effective_level = 20,
        zone = 100, exp = 1000, exp_needed = rules.tnl[75], lp = 9500, merits = 2,
        merit_cap = 10, limit_mode = true, dead = false }
    for key, value in pairs(values or {}) do result[key] = value end
    return result
end
local function award(state, amount, now, token)
    return state:award({ kind = 'lp', amount = amount, source = 'battle', chain = 3, token = token }, now)
end
local function reward_packet(message, amount, chain, actor, target)
    local bytes = MOCK.bytes(28)
    MOCK.put(bytes, 4, 4, actor or 100)
    MOCK.put(bytes, 8, 4, target or 100)
    MOCK.put(bytes, 16, 4, amount)
    MOCK.put(bytes, 20, 4, chain or 0)
    MOCK.put(bytes, 24, 2, message)
    return MOCK.packet(0x02D, bytes)
end

equal(rules.lp_per_merit, 10000, 'Phoenix LP conversion threshold')
for _, message in ipairs({ 371, 372 }) do
    local decoded = packets.awards(reward_packet(message, 1500, 4), 100)
    equal(#decoded, 1, 'LP reward message decoded')
    equal(decoded[1].kind, 'lp', 'LP reward never becomes EXP')
    equal(decoded[1].amount, 1500, 'LP reward amount preserved')
    equal(decoded[1].chain, 4, 'Limit chain preserved')
    equal(#packets.awards(reward_packet(message, 1500, 4, 200), 100), 0, 'Other player LP ignored')
    equal(#packets.awards(reward_packet(message, 1500, 4, 100, 200), 100), 0, 'Other target LP ignored')
end
equal(#packets.awards(reward_packet(50, 4), 100), 0, 'Stored merit message is not an LP reward')

for _, memory_first in ipairs({ false, true }) do
    local state = tracker.new()
    state:observe(snapshot(), 0)
    if memory_first then state:observe(snapshot({ lp = 1500, merits = 5 }), 1) end
    equal(award(state, 22000, memory_first and 1.1 or 1, 'multi'), true, 'Multiple-merit reward accepted')
    equal(award(state, 22000, 1.2, 'multi'), false, 'Duplicate LP reward ignored')
    if not memory_first then state:observe(snapshot({ lp = 1500, merits = 5 }), 1.3) end
    local view = state:view(61.1, { tracking = { window = 0 } })
    equal(view.mode, 'lp', 'Actual75 job keeps LP mode while synced20')
    equal(view.merits_gained, 3, 'Multiple conversions counted')
    equal(view.session_lp, 22000, 'Reported LP counted once')
    equal(view.net_lp, 22000, 'Multiple rollovers retain all LP')
    equal(view.adjustment, 0, 'Packet and memory orders reconcile')
    equal(view.merit_headroom, 5, 'Free stored merit slots')
    equal(view.merit_full, false, 'Available merit storage')
    equal(view.lp.blocked, false, 'Next merit available')
    equal(view.lp.reason, nil, 'No false storage warning')
    equal(view.lp.remaining, 8500, 'LP to next conversion')
    equal(view.chain, 3, 'LP award advances chain tracking')
    equal(view.session_exp, 0, 'LP does not affect EXP total')
    local prior = view.merits_gained
    state:observe(snapshot({ lp = 1500, merits = 0 }), 62)
    view = state:view(63)
    equal(view.merits_gained, prior, 'Spending leaves session merits earned intact')
    equal(view.net_lp, 22000, 'Spending leaves LP retained intact')
    equal(view.adjustment, 0, 'Spending is not a negative adjustment')
    equal(view.merit_headroom, 10, 'Spending restores storage slots')
end

for _, cap in ipairs({ 10, 30, 45 }) do
    local state = tracker.new()
    state:observe(snapshot({ merits = cap - 1, merit_cap = cap, lp = 0 }), 0)
    award(state, 25000, 1)
    state:observe(snapshot({ merits = cap, merit_cap = cap, lp = 5000 }), 1.1)
    local view = state:view(61, { tracking = { window = 0 } })
    equal(view.merits_gained, 1, 'Only available merit slot is filled')
    equal(view.session_lp, 25000, 'Reported reward includes cap overflow')
    equal(view.net_lp, 15000, 'Retained progress excludes cap overflow')
    equal(view.merit_headroom, 0, 'Client-reported merit capacity respected')
    equal(view.merit_full, true, 'Storage is full before LP buffer fills')
    equal(view.capped, false, 'LP buffer still has room')
    equal(view.lp.blocked, true, 'Full store blocks next merit')
    equal(view.eta, nil, 'No impossible main next-merit ETA')
    equal(view.lp.eta, nil, 'No impossible independent next-merit ETA')
    equal(view.lp.reason, 'Spend some merit points to make room for another.', 'Full storage explains action needed')
    equal(view.lp.remaining, 5000, 'Partial LP buffer remains visible')
    near(view.lp.rate, 1500000, 'Reported LP rate remains measured at cap')
    local net = state:view(61, { tracking = { window = 0, rate_basis = 'net' } })
    near(net.lp.rate, 900000, 'Retained LP rate excludes overflow')
    state:observe(snapshot({ merits = cap - 1, merit_cap = cap, lp = 5000 }), 62)
    view = state:view(63, { display = { mode = 'exp' } })
    equal(view.mode, 'exp', 'Explicit EXP display is retained')
    equal(view.lp.blocked, false, 'Spending reopens next merit while EXP displayed')
    equal(view.lp.eta ~= nil, true, 'Independent merit ETA returns after spending')
    equal(view.merit_headroom, 1, 'Free slot updates immediately')
    award(state, 5000, 64)
    state:observe(snapshot({ merits = cap, merit_cap = cap, lp = 0 }), 64.1)
    award(state, 15000, 65)
    state:observe(snapshot({ merits = cap, merit_cap = cap, lp = 9999 }), 65.1)
    view = state:view(70)
    equal(view.merits_gained, 2, 'Earning after spending counts another whole merit')
    equal(view.capped, true, 'Full store and 9,999 LP caps LP buffer')
    equal(view.lp.remaining, 0, 'Fully filled buffer has no remaining capacity')
    equal(view.net_lp, 29999, 'LP retained after spend and refill')
    equal(view.session_lp, 45000, 'All reported LP rewards retained in session')
end

local state = tracker.new()
state:observe(snapshot(), 0)
award(state, 1000, 1)
state:observe(snapshot({ lp = 500, merits = 3 }), 1.1)
state:pause(10, true)
award(state, 20000, 11)
state:observe(snapshot({ lp = 500, merits = 5 }), 11.1)
equal(state:view(12).merits_gained, 1, 'Paused conversions excluded')
state:pause(20, false)
state:observe(snapshot({ lp = 500, merits = 5 }), 20.1)
equal(state:view(21).net_lp, 1000, 'Paused LP does not leak into retained total')
local saved = state:export(21)
local restored = tracker.new()
equal(restored:restore(saved, 1000, { id = 100, job = 1 }), true, 'Merit session restores')
restored:observe(snapshot({ lp = 9000, merits = 9 }), 1000)
equal(restored:view(1000).merits_gained, 1, 'Offline conversions excluded')
equal(restored:view(1000).session_lp, 1000, 'LP total survives reload')
equal(restored:view(1000).net_lp, 1000, 'Retained LP survives reload')
restored:discontinuity(1001)
restored:observe(snapshot({ zone = 101, lp = 4000, merits = 10 }), 1002)
equal(restored:view(1002).merits_gained, 1, 'Zoning gap does not invent earned merits')
equal(restored:view(1002).net_lp, 1000, 'Zoning gap does not invent LP progress')
restored:reset(1003)
equal(restored:view(1003).merits_gained, 0, 'Reset clears session merits')
equal(restored:view(1003).merits, 10, 'Reset keeps stored merits visible')
equal(restored:view(1003).lp.current, 4000, 'Reset keeps current LP visible')

state = tracker.new()
local unknown = snapshot()
unknown.lp, unknown.merit_cap = nil, nil
state:observe(unknown, 0)
unknown.merits = 3
state:observe(unknown, 1)
local view = state:view(61)
equal(view.merits_gained, 1, 'Observed merit count does not require a known LP balance')
equal(view.net_lp, 0, 'Missing LP does not invent a retained gain')
equal(view.merit_headroom, nil, 'Unknown capacity stays unknown')
equal(view.lp.current, nil, 'Unknown LP stays unknown')
equal(view.lp.eta, nil, 'Unknown LP has no ETA')
equal(view.elapsed, 60, 'Observed whole merit starts the session')
local goal = goals.evaluate(unknown, view, { goal_type = 'session_merits', goal_session_merits = 1 }, {})
equal(goal.complete, true, 'Known earned goal remains complete with unknown LP')
goal = goals.evaluate(unknown, view, { goal_type = 'stored_merits', goal_merits = 3 }, {})
equal(goal.complete, true, 'Known stored goal remains complete with unknown LP')
goal = goals.evaluate(unknown, view, { goal_type = 'stored_merits', goal_merits = 4 }, {})
equal(goal.available, false, 'Unfinished stored goal requires LP balance')

for _, capacity in ipairs({ 0, -1, 0.5, math.huge }) do
    state = tracker.new()
    local pending = snapshot({ merits = 0, lp = 9999, merit_cap = capacity })
    state:observe(pending, 0)
    award(state, 1000, 1)
    view = state:view(61, { tracking = { window = 0 } })
    equal(view.merit_cap, nil, 'Invalid capacity stays unavailable')
    equal(view.merit_headroom, nil, 'Invalid capacity has no known storage slots')
    equal(view.merit_full, false, 'Invalid capacity is not proof of a full merit store')
    equal(view.capped, false, 'Invalid capacity is not proof of a full LP buffer')
    equal(view.lp.blocked, false, 'Invalid capacity does not ask players to spend merits')
    equal(view.lp.reason, 'Waiting for your merit point total and limit.', 'Unknown storage has a distinct explanation')
    equal(view.lp.eta, nil, 'Unknown capacity cannot promise the next merit')
    equal(view.eta, nil, 'Unknown capacity cannot promise a main next-merit ETA')
    equal(view.goal_eta, nil, 'Unknown capacity cannot promise a stored-goal ETA')
    goal = goals.evaluate(pending, view, { goal_type = 'stored_merits', goal_merits = 5 }, { lp = 60000 })
    equal(goal.target_merits, 5, 'Invalid capacity does not silently clamp target to one')
    equal(goal.complete, false, 'Invalid capacity cannot complete an unearned stored goal')
    equal(goal.eta, nil, 'Unknown storage prevents an impossible goal ETA')
    equal(goal.reason, 'Waiting for your merit point total and limit.', 'Unknown capacity is explained')
end

