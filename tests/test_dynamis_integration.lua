local defaults = require('ui.defaults');
local history = require('ui.history');
local profiles = require('ui.profiles');
local store = require('core.file_store');
local count = 0;
local function eq(a, b, label) count = count + 1; assert(a == b, label .. ': ' .. tostring(a) .. ' ~= ' .. tostring(b)); end
require('ui.hud').draw = function() return false; end;
dofile(ADDON_DIR .. '/momentum.lua');
MOCK.fire('load');
local app = MOMENTUM_TEST;
local s = app.settings();
s.display.labels.rate = 'My EXP/HR';
s.display.alignment = 'right';
s.display.auto_layout = true;
local normal = history.copy(s.display);
local utc = os.time();
MOCK.player.zone = 185;
app.sample(1);
app.dynamis.core:hourglass({ zone = 185, start_time = utc, end_time = utc + 3600 }, 1, utc);
MOCK.now = 1;
MOCK.frame(0.25);
eq(app.state.broken, false, 'Dynamis entry renders');
eq(s.dynamis.layout_active, true, 'Dynamis auto layout');
eq(s.display.enabled.dyna_time, true, 'Dynamis time shown');
eq(s.display.alignment, 'left', 'Compact layout left aligned');
eq(history.equal(s.dynamis.previous_display, normal), true, 'Exact EXP layout preserved');
s.display.labels.dyna_time = 'Left';
local captured = profiles.capture(s);
eq(captured.display.labels.rate, 'My EXP/HR', 'Profile captures normal layout');
eq(captured.dynamis.layout.labels.dyna_time, 'Left', 'Profile captures edited Dynamis layout');
eq(captured.dynamis.layout_active, false, 'Profile has no transient active marker');
local legacy = { display = history.copy(normal) };
legacy.display.labels.rate = 'Legacy EXP/HR';
profiles.apply(s, legacy);
eq(s.dynamis.layout_active, false, 'Legacy profile leaves transient layout');
eq(s.dynamis.layout.labels.dyna_time, 'Left', 'Legacy profile keeps Dynamis edits');
eq(s.display.labels.rate, 'Legacy EXP/HR', 'Legacy profile replaces normal display');
MOCK.frame(0.25);
eq(s.dynamis.layout_active, true, 'New normal profile re-enters Dynamis');
normal.labels.rate = 'Legacy EXP/HR';
app.services.reset_section('dynamis');
MOCK.frame(0.25);
eq(history.equal(s.dynamis.previous_display, normal), true, 'Dynamis section reset preserves normal layout');
s.display.labels.dyna_time = 'Left';
local before = app.view(2).dynamis.remaining;
app.services.session_pause(true);
eq(app.view(2).dynamis.remaining, before, 'EXP Pause preserves Dynamis timer');
app.services.session_reset();
eq(app.view(2).dynamis.remaining, before, 'EXP Reset preserves Dynamis timer');
app.dynamis.core:drop({ slot = 0, item_id = 1456, count = 1, start_time = 55, token = 'one' }, 2, utc);
app.services.session_reset();
eq(app.view(2).dynamis.currency_found, 100, 'EXP Reset preserves loot totals');
MOCK.player.zone = 102;
app.sample(3);
MOCK.now = 3;
MOCK.frame(0.25);
eq(s.dynamis.layout_active, false, 'Exit restores normal layout');
eq(history.equal(s.display, normal), true, 'Custom normal layout unchanged');
eq(s.dynamis.layout.labels.dyna_time, 'Left', 'Dynamis edits retained');
eq(#app.services.dynamis_history(), 1, 'Run saved on exit');
s.window.open = true;
app.services.dynamis_layout('dynamis');
MOCK.frame(0.25);
eq(s.dynamis.layout_active, true, 'Edit Dynamis layout outside zone');
app.services.dynamis_layout('normal');
MOCK.frame(0.25);
eq(s.dynamis.layout_active, false, 'Return to normal editing');
s.dynamis.auto_layout = false;
app.services.dynamis_layout('dynamis');
s.window.open = false;
MOCK.frame(0.25);
eq(s.dynamis.layout_active, true, 'Manual layout stays selected with automatic switching off');
app.services.dynamis_layout('normal');
MOCK.frame(0.25);
eq(s.dynamis.layout_active, false, 'Manual return stays normal');
MOCK.fire('unload');
assert(not app.dynamis.saved_error, app.dynamis.saved_error);
local path = MOCK_INSTALL_PATH .. '/config/addons/momentum/dynamis-1001.json';
local saved = assert(store.read(path));
eq(saved.player_id, 1001, 'Character run persistence');
eq(#saved.history, 1, 'Persisted run history');
local runtime = require('core.dynamis_runtime').new(MOCK_INSTALL_PATH .. '/config/addons/momentum/', { clock = function() return utc; end });
runtime:sample({ valid = true, id = 1001, zone = 102 }, 10, s);
eq(#runtime:view(10, s).history, 1, 'History reload');
local other = history.copy(saved); other.history = {};
assert(store.write(path, other));
runtime.core:registration(185, 11, utc);
eq(runtime:save(11, true), false, 'Concurrent client save protected');
eq(#assert(store.read(path)).history, 0, 'External file preserved');
eq(runtime:view(11, s).saved_error ~= nil, true, 'Save conflict visible');
runtime:detach(12);
assert(store.write(path, { version = 99, player_id = 1001 }));
runtime:sample({ valid = true, id = 1001, zone = 185 }, 13, s);
runtime.core:hourglass({ zone = 185, start_time = utc, end_time = utc + 3600 }, 13, utc);
eq(runtime:save(14, true), false, 'Malformed history protected');
eq(assert(store.read(path)).version, 99, 'Malformed original kept');
return { count = count };
