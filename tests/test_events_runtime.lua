local runtime = require('core.events_runtime');
local store = require('core.file_store');
local rules = require('data.event_rules');
local history = require('ui.history');
local count = 0;
local function eq(a, b, name) count = count + 1; assert(a == b, name .. ': ' .. tostring(a) .. ' ~= ' .. tostring(b)); end
local utc, settings = 1800000000, { events = { enabled = true } };
local folder = MOCK_INSTALL_PATH .. '/config/addons/momentum/';
local memory = { GetInventory = function() return {}; end, GetPlayer = function() return { HasKeyItem = function() return false; end }; end };
local tracker = runtime.new(folder, { clock = function() return utc; end, memory = memory });
tracker:sample({ valid = true, id = 1001, zone = 102 }, 0, settings);
eq(tracker:view(5, settings).zone_elapsed, 5, 'Runtime zone timer');
eq(tracker:save(1, false), true, 'Clean or throttled save succeeds');
tracker.core:cooldown('enm:8', 'Bearclaw Pinnacle', utc + 1000, utc, 'ENM timer NPC', false);
eq(tracker:save(31, false), true, 'Dirty periodic save');
local path = folder .. 'events-1001.json';
local saved = assert(store.read(path));
eq(saved.player_id, 1001, 'Character-specific persistence');
eq(saved.cooldowns['enm:8'].ready_at, utc + 1000, 'Absolute cooldown persisted');
local restored = runtime.new(folder, { clock = function() return utc; end, memory = memory });
restored:sample({ valid = true, id = 1001, zone = 102 }, 40, settings);
eq(restored:view(40, settings).cooldowns[1].remaining, 1000, 'Cooldown restored without guessing entry');
local other = history.copy(saved);
other.cooldowns = {};
assert(store.write(path, other));
restored.core:currency({ assault_tags = 2 }, utc);
eq(restored:save(41, true), false, 'Concurrent client save protected');
eq(next(assert(store.read(path)).cooldowns), nil, 'External data kept');
eq(restored:view(41, settings).saved_error ~= nil, true, 'Save conflict visible');
restored:detach(42);
assert(store.write(path, { schema = 99, player_id = 1001 }));
restored:sample({ valid = true, id = 1001, zone = 102 }, 43, settings);
restored.core:currency({ assault_tags = 1 }, utc);
eq(restored:save(44, true), false, 'Unknown schema protected');
eq(assert(store.read(path)).schema, 99, 'Malformed original kept');
return { count = count };
