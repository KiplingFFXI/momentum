local defaults = require('ui.defaults');
local history = require('ui.history');
local modes = require('ui.modes');
local profiles = require('ui.profiles');
local checks = 0;
local function equal(actual, expected, label)
    checks = checks + 1;
    assert(actual == expected, label .. ': expected ' .. tostring(expected) .. ', got ' .. tostring(actual));
end

local old = defaults.make();
local old_automatic = history.copy(old.display);
old.modes = { selected = 'auto', exp = history.copy(old.display), merits = {}, previous_display = {} };
old.modes.exp.enabled.food = true;
old.modes.exp.labels.food = 'Saved food';
defaults.tidy(old);
equal(old.display.enabled.food, true, 'Old saved EXP additions appear in Automatic');
equal(old.display.labels.food, 'Saved food', 'Old saved EXP labels appear in Automatic');
equal(history.equal(old.modes.previous_display, old_automatic), true, 'The differing old Automatic layout is kept');
equal(old.modes.active, 'exp', 'Old EXP layout receives an explicit identity');
equal(old.modes.layout_version, 1, 'Migration is marked complete');
old.display.labels.food = 'New Auto food';
defaults.tidy(old);
equal(old.display.labels.food, 'New Auto food', 'Later tidying does not replay the old layout migration');
modes.select(old, 'merits');
modes.select(old, 'exp');
equal(old.display.labels.food, 'New Auto food', 'New Automatic edits are also used in manual EXP');
old.display.enabled.ring = true;
old.display.labels.ring = 'Ring ready';
modes.select(old, 'auto');
equal(old.display.enabled.ring, true, 'New manual EXP additions are also used in Automatic');
equal(old.display.labels.ring, 'Ring ready', 'New manual EXP labels are also used in Automatic');
equal(old.display.mode, 'auto', 'Manual EXP does not force the Automatic points preference');

local manual = defaults.make();
local previous = history.copy(manual.display);
previous.mode, previous.auto_layout = 'lp', true;
manual.modes = { selected = 'exp', exp = history.copy(manual.display), merits = {}, previous_display = previous };
manual.display.mode = 'exp';
manual.display.enabled.food = true;
manual.display.labels.food = 'Latest manual food';
defaults.tidy(manual);
equal(manual.display.enabled.food, true, 'Current manual edits win over a stale saved copy');
equal(manual.modes.exp.labels.food, 'Latest manual food', 'Current manual edits seed the shared bank');
equal(history.equal(manual.modes.previous_display, previous), true, 'The previous Automatic layout remains available');
modes.select(manual, 'auto');
equal(manual.display.mode, 'lp', 'The previous Automatic points preference is restored');
equal(manual.display.auto_layout, true, 'The previous automatic switching preference is restored');
equal(manual.display.enabled.food, true, 'Returning Automatic retains the latest manual readouts');
modes.automatic(manual, 'lp');
equal(manual.modes.active, 'merits', 'Automatic can switch after migration');
manual.display.labels.lp_rate = 'Saved LP';
manual.display.enabled.job = true;
modes.automatic(manual, 'exp');
equal(manual.display.labels.food, 'Latest manual food', 'Automatic returns to the migrated EXP bank');
equal(manual.display.mode, 'lp', 'Automatic bank swaps preserve the selected points preference');
equal(manual.display.auto_layout, true, 'A saved bank never turns switching off');
modes.automatic(manual, 'lp');
equal(manual.display.labels.lp_rate, 'Saved LP', 'Automatic retains new Merits labels');
equal(manual.display.enabled.job, true, 'Automatic retains new Merits additions');

local profile = profiles.capture(manual);
local restored = defaults.make();
profiles.apply(restored, profile);
defaults.tidy(restored);
equal(restored.display.labels.lp_rate, 'Saved LP', 'Profiles preserve current Automatic edits');
modes.automatic(restored, 'exp');
equal(restored.display.labels.food, 'Latest manual food', 'Profiles preserve the other Automatic bank');
modes.select(restored, 'dynamis');
restored.display.labels.dyna_time = 'Dyna left';
local dynamis_profile = profiles.capture(restored);
profiles.apply(restored, dynamis_profile);
defaults.tidy(restored);
modes.select(restored, 'exp');
equal(restored.display.labels.food, 'Latest manual food', 'A Dynamis profile preserves the EXP bank');
modes.select(restored, 'merits');
equal(restored.display.labels.lp_rate, 'Saved LP', 'A Dynamis profile preserves the Merits bank');
modes.select(restored, 'dynamis');
equal(restored.display.labels.dyna_time, 'Dyna left', 'A Dynamis profile preserves the Dynamis layout');

local conflicting = defaults.make();
local older = history.copy(conflicting.display);
older.labels.rate = 'Older Automatic';
conflicting.display.labels.rate = 'Current Automatic';
conflicting.modes = { selected = 'auto', exp = history.copy(conflicting.display), merits = {}, previous_display = older };
conflicting.modes.exp.labels.rate = 'Saved manual EXP';
defaults.tidy(conflicting);
equal(conflicting.display.labels.rate, 'Saved manual EXP', 'Saved manual bank fixes the reported missing-readout case');
equal(conflicting.modes.previous_display.labels.rate, 'Older Automatic', 'An existing compatibility copy is never overwritten');
equal(conflicting.modes.legacy_auto_display.labels.rate, 'Current Automatic', 'A second differing legacy layout is retained separately');
return { count = checks };
