local worker = require('core.sound_worker');
local count = 0;
local function eq(actual, expected, label)
    count = count + 1;
    assert(actual == expected, label .. ': ' .. tostring(actual) .. ' ~= ' .. tostring(expected));
end
local source = worker.new('C:\\Momentum Folder\\bin\\momentum-sound.exe');
eq(source:owned(), false, 'Construction owns no handles');
eq(MOCK.sound_workers, nil, 'Construction does not launch');
eq(source:start('C:\\My sounds\\test.mp3', 500), true, 'A quoted sound starts');
local first = MOCK.sound_workers[1];
source:update(0);
eq(first.cmd, '"C:\\Momentum Folder\\bin\\momentum-sound.exe" "C:\\My sounds\\test.mp3" 500 1234 ""', 'Arguments stay separate');
eq(first.startup.cb, 68, 'x86 startup structure size');
eq(first.thread.closed, true, 'Unused thread handle closes');
source:update(1);
local polls = MOCK.sound_polls;
for index = 1, 20 do source:update(1 + index / 100); end
eq(MOCK.sound_polls, polls, 'Active polling stays below four times a second');
source:update(1.25);
eq(MOCK.sound_polls, polls + 1, 'A due poll runs');
first.process.code = 7;
local outcome = source:update(1.5);
eq(outcome.code, 7, 'Worker timeout reaches the parent');
eq(type(outcome.problem), 'string', 'Worker failure has a player message');
eq(first.process.closed, true, 'Finished process handle closes');
eq(source:owned(), false, 'Finished playback owns no handles');
local attempts = MOCK.sound_polls;
for index = 1, 100 do source:update(2 + index); end
eq(MOCK.sound_polls, attempts, 'Idle playback does not poll');
source:start('C:\\test.wav', 400);
source:update(199);
local second = MOCK.sound_workers[2];
MOCK.sound_terminate_pending = true;
eq(source:start('C:\\next.wav', 300), true, 'Replacement is accepted while cancellation finishes');
eq(#MOCK.sound_workers, 2, 'No overlapping child launches');
eq(source.pending.path, 'C:\\next.wav', 'One replacement is kept');
source:start('C:\\latest.wav', 200);
eq(source.pending.path, 'C:\\latest.wav', 'A later replacement supersedes the pending request');
eq(second.process.closed, nil, 'An active child handle remains owned');
eq(MOCK.sound_waits, nil, 'The game never waits for a child');
second.process.code = 1;
MOCK.sound_terminate_pending = nil;
source:update(200);
eq(second.process.closed, true, 'Cancelled process is reaped');
eq(#MOCK.sound_workers, 3, 'The latest request starts after cancellation');
eq(MOCK.sound_workers[3].path, 'C:\\latest.wav', 'The superseded request never plays');
source:update(200.25);
MOCK.sound_terminate_error = true;
source:start('C:\\cancelled.wav', 300);
eq(source:owned(), true, 'Failed termination keeps ownership');
eq(#MOCK.sound_workers, 3, 'Failed termination does not accumulate children');
source:stop();
eq(source.pending, nil, 'Close discards pending playback');
MOCK.sound_terminate_error = nil;
source:update(201);
eq(source:owned(), false, 'Deferred cancellation recovers');
eq(#MOCK.sound_workers, 3, 'Closed playback never launches later');
source:start('C:\\test.wav', 400);
source:update(201.5);
local fourth = MOCK.sound_workers[4];
MOCK.sound_close_error = true;
eq(source:stop(), false, 'A failed handle close remains owned');
eq(source:owned(), true, 'Failed cleanup retains its handle');
MOCK.sound_close_error = nil;
source:update(202);
eq(source:owned(), false, 'Retained handle cleanup recovers');
eq(fourth.process.closed, true, 'Retained handle closes once');
source:set_trace(function(_, fields)
    for _, value in pairs(fields) do assert(type(value) ~= 'string' or not value:find('Private', 1, true)); end
end, 'C:\\Private Folder\\sound.log');
source:start('C:\\My sounds\\test.mp3', 500);
eq(MOCK.sound_workers[5].cmd:find('1234 "C:\\Private Folder\\sound.log"', 1, true) ~= nil, true, 'Diagnostic path is a separate quoted argument');
source:update(203);
MOCK.sound_terminate_pending = true;
source:start('C:\\do-not-play.wav', 500);
local terminations = MOCK.sound_terminations;
MOCK.sound_terminate_error = true;
eq(source:shutdown(), true, 'Unload requests cancellation and releases owned handles without waiting');
eq(MOCK.sound_terminations, terminations, 'Unload does not repeat an already accepted termination request');
eq(source.pending, nil, 'Unload clears replacement playback');
eq(source:owned(), false, 'Unload leaves no owned handles after termination is accepted');
MOCK.sound_terminate_pending = nil;
MOCK.sound_terminate_error = nil;
local total = #MOCK.sound_workers;
eq(source:start('C:\\bad\0sound.mp3', 500), false, 'Embedded NUL rejected');
eq(source:start('C:\\test.mp3', 0 / 0), false, 'NaN volume rejected');
eq(source:start('C:\\test.mp3', 1001), false, 'Out-of-range volume rejected');
eq(#MOCK.sound_workers, total, 'Invalid input never launches');
return { count = count };
