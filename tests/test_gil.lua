local gil = require('core.gil')
local json = require('json')
local checks = 0
local function equal(a, b, label)
    checks = checks + 1
    assert(a == b, label .. ': expected ' .. tostring(b) .. ', got ' .. tostring(a))
end
local function near(a, b, label)
    checks = checks + 1
    assert(a and math.abs(a - b) < 0.001, label .. ': expected ' .. b .. ', got ' .. tostring(a))
end
local state = gil.new()
equal(state:view(0).current, nil, 'Unknown balance is not zero')
equal(state:view(0).rate, nil, 'No rate before a counted change')
equal(state:observe(10000, 0), true, 'First balance accepted')
equal(state:view(100).gained, 0, 'Initial wallet is not income')
equal(state:view(100).elapsed, 0, 'No clock before first change')
state:observe(11000, 100)
state:observe(10700, 110)
state:observe(10700, 111)
equal(state:view(159).rate, nil, 'Rate waits sixty active seconds')
local view = state:view(160)
equal(view.current, 10700, 'Current balance includes spending')
equal(view.gained, 1000, 'Incoming gil counted')
equal(view.spent, 300, 'Outgoing gil counted')
equal(view.net, 700, 'Net subtracts spending')
near(view.rate, 42000, 'Gil per hour uses net change')
for _, invalid in ipairs({ -1, 1000000000, 1.5, '100', false, math.huge, -math.huge, 0 / 0, {} }) do
    equal(state:observe(invalid, 161), false, 'Malformed balance rejected')
end
equal(state:observe(nil, 161), false, 'Missing balance rejected')
equal(state:view(161).current, 10700, 'Bad samples do not replace known balance')
state:observe(1000, 161, true)
equal(state:view(161).net, 700, 'Explicit baseline update never counts spending')
state:set_paused(true, 170)
state:observe(1500, 200)
state:observe(1400, 250)
view = state:view(300)
equal(view.current, 1400, 'Current gil keeps updating while paused')
equal(view.gained, 1000, 'Paused gains excluded')
equal(view.spent, 300, 'Paused spending excluded')
equal(view.elapsed, 70, 'Paused clock frozen')
state:set_paused(true, 300)
state:set_paused(false, 400)
state:observe(1300, 401)
view = state:view(410)
equal(view.spent, 400, 'Resume compares with latest paused balance')
equal(view.elapsed, 80, 'Pause duration excluded')
state:discontinuity(420)
equal(state:view(1000).current, nil, 'A gap clears current gil')
equal(state:view(1000).elapsed, 90, 'A gap freezes gil time')
state:discontinuity(1001)
state:observe(999999999, 1010)
equal(state:view(1010).gained, 1000, 'First balance after gap is not income')
state:observe(999999998, 1020)
equal(state:view(1020).spent, 401, 'Changes after new baseline count')
equal(state:view(1020).elapsed, 100, 'Clock resumes after gap baseline')

local saved = json.decode(json.encode(state:export(1020)))
equal(saved.current, nil, 'Wallet is not persisted')
equal(saved.baseline, nil, 'Comparison baseline is not persisted')
local resumed = gil.new()
equal(resumed:restore(saved, 10000), true, 'Gil session survives JSON round trip')
equal(resumed:view(10100).current, nil, 'Restore waits for current wallet')
equal(resumed:view(10100).elapsed, 100, 'Restore excludes time before fresh balance')
resumed:observe(0, 10100)
equal(resumed:view(10100).spent, 401, 'Unloaded spending never backfilled')
equal(resumed:view(10100).current, 0, 'Zero balance is valid')
resumed:observe(100, 10101)
equal(resumed:view(10101).gained, 1100, 'New income counts after restore')
equal(resumed:view(10101).elapsed, 101, 'Restored clock continues')
resumed:reset(10102)
view = resumed:view(10102)
equal(view.current, 100, 'Reset preserves current wallet')
equal(view.gained, 0, 'Reset clears gains')
equal(view.spent, 0, 'Reset clears spending')
equal(view.net, 0, 'Reset clears net')
equal(view.elapsed, 0, 'Reset clears gil clock')
equal(view.rate, nil, 'Reset clears rate immediately')
resumed:observe(90, 10103)
near(resumed:view(10163).rate, -600, 'Spending-only session has negative rate')
resumed:set_paused(true, 10163)
resumed:reset(10164)
resumed:observe(200, 10165)
equal(resumed.paused, true, 'Reset preserves pause choice')
equal(resumed:view(10200).gained, 0, 'Reset while paused does not resume counting')
equal(resumed:view(10200).elapsed, 0, 'Reset paused clock stays stopped')

for _, change in ipairs({
    { 'version', 2 }, { 'gained', -1 }, { 'gained', 0.5 }, { 'gained', 1000000000001 },
    { 'spent', '1' }, { 'spent', math.huge }, { 'elapsed', -1 }, { 'elapsed', 0 / 0 },
    { 'elapsed', 315360001 }, { 'started', false }, { 'paused', 1 },
}) do
    local bad = json.decode(json.encode(saved))
    bad[change[1]] = change[2]
    equal(resumed:restore(bad, 0), false, 'Malformed saved gil rejected: ' .. change[1])
    equal(resumed:view(10200).current, 200, 'Rejected restore keeps current state')
end
equal(resumed:restore({ version = 1, gained = 0, spent = 0, elapsed = 0, started = true, paused = false }, 0), false,
    'Started clock requires a counted change')
equal(resumed:restore({ version = 1, gained = 0, spent = 0, elapsed = 1, started = false, paused = false }, 0), false,
    'Elapsed time requires a started clock')
state = gil.new()
state:observe(100, 10)
state:observe(200, 20)
state:view(80)
equal(state:view(30).elapsed, 60, 'Clock rollback cannot reverse elapsed time')
return checks .. ' assertions'
